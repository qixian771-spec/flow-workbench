"""Deterministically package the existing Seko adapters. Standard library only."""
import argparse
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCES=['scripts/seko_local_assembly_page.js','scripts/seko_local_multishot_page.js',
         'scripts/seko_local_workflow_page.js','scripts/seko_local_resident_page.js']
DEST=ROOT/'extension/seko_local_bundle.js'


def bundle():
    chunks=[]
    for name in SOURCES:
        source=(ROOT/name).read_text()
        chunks.append(f'// SOURCE {name} SHA256 {hashlib.sha256(source.encode()).hexdigest()}\n'+source)
    return ('/* Generated by scripts/build_seko_local_bundle.py; edit the named sources. */\n'+
            '(()=>{\n'+ '\n'.join(chunks)+'\ninstallSekoLocalResident();\n})();\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();source=bundle()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=source:raise SystemExit('Packaged Seko adapters are stale')
        print('Packaged adapters match all source files')
    else:DEST.write_text(source);print('Built '+str(DEST))
